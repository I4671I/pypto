"""Unit tests for the Kunpeng SVE C code generator (pypto.ir.sve_codegen)."""

import ctypes
import json
import shutil
import subprocess

import numpy as np
import pypto.language as pl
import pytest
from pypto.ir import sve_codegen


def _vector_add(n: int):
    @pl.program
    class VectorAdd:
        @pl.function(type=pl.FunctionType.InCore)
        def vector_add(
            self,
            a: pl.Tensor[[n], pl.FP32],
            b: pl.Tensor[[n], pl.FP32],
            c: pl.Out[pl.Tensor[[n], pl.FP32]],
        ) -> pl.Tensor[[n], pl.FP32]:
            a_part = pl.tensor.slice(a, [n], [0])
            b_part = pl.tensor.slice(b, [n], [0])
            result = pl.add(a_part, b_part)
            c = pl.tensor.assemble(c, result, [0])
            return c

    return VectorAdd


def _lower(program):
    # sve_codegen.lower never configures an NPU backend; the autouse
    # _reset_backend_singleton fixture guarantees none is left over either.
    return sve_codegen.lower(program)


def test_vector_add_matches_reference_kernel():
    """The default target reproduces the reference Vector Add kernel line for line."""
    files = sve_codegen.generate(_lower(_vector_add(1000)))

    assert sorted(files) == ["kernels/sve/vector_add.c", "kernels/sve/vector_add.json"]
    assert files["kernels/sve/vector_add.c"] == (
        "// Generated by pypto.ir.sve_codegen from InCore function 'vector_add'.\n"
        "// Processes elements [0, n); callers pass n <= 1000, the tile length.\n"
        "#include <stdint.h>\n"
        "\n"
        "void vector_add_kernel(float* a, float* b, float* c, int64_t n) {\n"
        "    #pragma clang loop vectorize(enable) interleave(disable)\n"
        "    for (int64_t i = 0; i < n; i++) {\n"
        "        c[i] = a[i] + b[i];\n"
        "    }\n"
        "}\n"
    )


def test_build_config_records_target_and_signature():
    files = sve_codegen.generate(_lower(_vector_add(16)))
    config = json.loads(files["kernels/sve/vector_add.json"])

    assert config["symbol"] == "vector_add_kernel"
    assert config["source"] == "vector_add.c"
    assert config["n"] == 16
    assert config["compiler"] == "clang"
    assert config["flags"] == ["-O3", "-march=armv8.2-a+sve", "-msve-vector-bits=512"]
    assert config["streaming"] is False
    assert [(p["name"], p["direction"], p["dtype"], p["shape"]) for p in config["params"]] == [
        ("a", "In", "fp32", [16]),
        ("b", "In", "fp32", [16]),
        ("c", "Out", "fp32", [16]),
    ]


def test_vector_length_agnostic_target_omits_vector_bits():
    target = sve_codegen.SVETargetConfig(vector_bits=None, interleave=True)
    files = sve_codegen.generate(_lower(_vector_add(16)), target)

    assert json.loads(files["kernels/sve/vector_add.json"])["flags"] == ["-O3", "-march=armv8.2-a+sve"]
    assert "#pragma clang loop vectorize(enable) interleave(enable)" in files["kernels/sve/vector_add.c"]


def test_streaming_target_marks_kernel_for_sme():
    target = sve_codegen.SVETargetConfig(march="armv9-a+sme", streaming=True)
    source = sve_codegen.generate(_lower(_vector_add(16)), target)["kernels/sve/vector_add.c"]

    assert "void vector_add_kernel(float* a, float* b, float* c, int64_t n) __arm_streaming {" in source


