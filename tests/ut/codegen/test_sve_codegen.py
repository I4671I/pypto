def test_offsets_and_chained_ops_fuse_into_one_loop():
    """Offsets become index shifts, and nested binary ops keep their grouping."""

    @pl.program
    class Window:
        @pl.function(type=pl.FunctionType.InCore)
        def axpy(
            self,
            a: pl.Tensor[[32], pl.FP32],
            b: pl.Tensor[[32], pl.FP32],
            c: pl.Out[pl.Tensor[[16], pl.FP32]],
        ) -> pl.Tensor[[16], pl.FP32]:
            a_part = pl.tensor.slice(a, [16], [16])
            b_part = pl.tensor.slice(b, [16], [16])
            total = pl.add(a_part, b_part)
            scaled = pl.mul(total, a_part)
            c = pl.tensor.assemble(c, scaled, [0])
            return c

    source = sve_codegen.generate(_lower(Window))["kernels/sve/axpy.c"]

    assert "        c[i] = (a[i + 16] + b[i + 16]) * a[i + 16];\n" in source


def _two_stores(second_offset: int):
    """Store a + b at offset 0 and a - b at ``second_offset`` of a 32-element output."""

    @pl.program
    class TwoStores:
        @pl.function(type=pl.FunctionType.InCore)
        def sum_and_diff(
            self,
            a: pl.Tensor[[16], pl.FP32],
            b: pl.Tensor[[16], pl.FP32],
            c: pl.Out[pl.Tensor[[32], pl.FP32]],
        ) -> pl.Tensor[[32], pl.FP32]:
            a_part = pl.tensor.slice(a, [16], [0])
            b_part = pl.tensor.slice(b, [16], [0])
            c = pl.tensor.assemble(c, pl.add(a_part, b_part), [0])
            c = pl.tensor.assemble(c, pl.sub(a_part, b_part), [second_offset])
            return c

    return TwoStores


def test_disjoint_stores_to_one_output_fuse():
    """The second store's destination is the tensor the first store returned."""
    source = sve_codegen.generate(_lower(_two_stores(16)))["kernels/sve/sum_and_diff.c"]

    assert "        c[i] = a[i] + b[i];\n        c[i + 16] = a[i] - b[i];\n" in source


def test_rejects_overlapping_stores_to_one_output():
    """Windows [0, 16) and [8, 24) overlap.

    Sequentially, c[8:16] ends up holding a - b. The fused loop would let
    iteration i + 8 overwrite c[i + 8] with a + b after iteration i stored
    a - b there, so codegen must refuse instead of emitting it.
    """
    with pytest.raises(ValueError, match="overlap"):
        sve_codegen.generate(_lower(_two_stores(8)))


def test_rejects_non_fp32_tensors():
    @pl.program
    class Half:
        @pl.function(type=pl.FunctionType.InCore)
        def add_fp16(
            self,
            a: pl.Tensor[[16], pl.FP16],
            b: pl.Tensor[[16], pl.FP16],
            c: pl.Out[pl.Tensor[[16], pl.FP16]],
        ) -> pl.Tensor[[16], pl.FP16]:
            a_part = pl.tensor.slice(a, [16], [0])
            b_part = pl.tensor.slice(b, [16], [0])
            c = pl.tensor.assemble(c, pl.add(a_part, b_part), [0])
            return c

    with pytest.raises(ValueError, match="only fp32 is supported"):
        sve_codegen.generate(_lower(Half))


def test_rejects_multidimensional_tensors():
    @pl.program
    class Matrix:
        @pl.function(type=pl.FunctionType.InCore)
        def add_2d(
            self,
            a: pl.Tensor[[4, 8], pl.FP32],
            b: pl.Tensor[[4, 8], pl.FP32],
            c: pl.Out[pl.Tensor[[4, 8], pl.FP32]],
        ) -> pl.Tensor[[4, 8], pl.FP32]:
            a_part = pl.tensor.slice(a, [4, 8], [0, 0])
            b_part = pl.tensor.slice(b, [4, 8], [0, 0])
            c = pl.tensor.assemble(c, pl.add(a_part, b_part), [0, 0])
            return c

    with pytest.raises(ValueError, match="only 1-D data is supported"):
        sve_codegen.generate(_lower(Matrix))


def test_compile_to_files_writes_kernel_and_config(tmp_path):
    files = sve_codegen.compile_to_files(_vector_add(64), str(tmp_path))

    for relative_path, content in files.items():
        assert (tmp_path / relative_path).read_text(encoding="utf-8") == content


def _host_c_compiler() -> str | None:
    return next((cc for cc in ("cc", "gcc", "clang") if shutil.which(cc)), None)


@pytest.mark.skipif(_host_c_compiler() is None, reason="no host C compiler available")
@pytest.mark.parametrize("n", [1, 15, 16, 17, 1000])
def test_generated_kernel_is_bit_exact_on_host(tmp_path, n):
    """Run the generated C on the host CPU and compare with a float32 reference.

    The host build omits the SVE flags: this checks the kernel's semantics and
    tail handling, while SVE code generation is checked on the target. Lengths
    around 16 cover tails for 512-bit vectors (16 fp32 lanes).
    """
    sve_codegen.compile_to_files(_vector_add(n), str(tmp_path))
    library = tmp_path / "vector_add.so"
    compiler = _host_c_compiler()
    assert compiler is not None
    source = tmp_path / "kernels/sve/vector_add.c"
    subprocess.run([compiler, "-O2", "-shared", "-fPIC", "-o", str(library), str(source)], check=True)

    rng = np.random.default_rng(n)
    a = rng.standard_normal(n).astype(np.float32)
    b = rng.standard_normal(n).astype(np.float32)
    c = np.zeros(n, dtype=np.float32)
    kernel = ctypes.CDLL(str(library)).vector_add_kernel
    pointer = ctypes.POINTER(ctypes.c_float)
    kernel.argtypes = [pointer, pointer, pointer, ctypes.c_int64]
    kernel(*(x.ctypes.data_as(pointer) for x in (a, b, c)), n)

    # np.add with float32 operands rounds every element to float32, like C.
    expected = np.add(a, b, dtype=np.float32)
    assert np.array_equal(c.view(np.uint32), expected.view(np.uint32))


if __name__ == "__main__":
    pytest.main([__file__, "-v"])
